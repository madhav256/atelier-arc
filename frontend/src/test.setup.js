import '@testing-library/jest-dom';

// jsdom does not implement matchMedia; motion libraries and the gallery's
// reduced-motion checks expect it.
if (!window.matchMedia) {
  window.matchMedia = (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  });
}
